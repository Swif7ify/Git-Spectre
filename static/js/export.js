/**
 * Export Component
 * Client-side PDF export (jsPDF), shareable PNG card generation (html2canvas), and README badge snippet.
 */

import { showToast, compact, full, avatarUrl, icon } from './utils.js';

export async function exportPdf(dossier) {
  if (!dossier || !dossier.profile) {
    showToast('No profile scanned yet', 'alert-triangle');
    return;
  }

  showToast('Generating PDF dossier…', 'file-text');
  try {
    const { jsPDF } = window.jspdf;
    const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
    const profile = dossier.profile;
    const score = dossier.score || {};
    const archetype = dossier.archetype || {};
    const stats = dossier.stats || {};

    // Page background
    doc.setFillColor(9, 9, 11);
    doc.rect(0, 0, 210, 297, 'F');

    // Header title
    doc.setTextColor(198, 244, 50); // Lime
    doc.setFont('courier', 'bold');
    doc.setFontSize(16);
    doc.text('GIT-SPECTRE // DEVELOPER DOSSIER', 14, 20);

    // Profile details
    doc.setTextColor(240, 240, 243);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(22);
    doc.text(profile.name || profile.login, 14, 34);

    doc.setTextColor(139, 108, 255); // Accent
    doc.setFont('courier', 'normal');
    doc.setFontSize(12);
    doc.text(`@${profile.login}  |  github.com/${profile.login}`, 14, 42);

    doc.setTextColor(150, 150, 162);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    const bioLines = doc.splitTextToSize(profile.bio || 'No public bio provided.', 180);
    doc.text(bioLines, 14, 50);

    // Divider
    doc.setDrawColor(39, 39, 46);
    doc.line(14, 62, 196, 62);

    // Developer Score & Archetype
    doc.setTextColor(240, 240, 243);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(14);
    doc.text(`DEVELOPER SCORE: ${score.total || 0}/1000 (${score.grade || 'E'})`, 14, 72);

    doc.setTextColor(198, 244, 50);
    doc.setFont('courier', 'bold');
    doc.setFontSize(11);
    doc.text(`ARCHETYPE: ${archetype.label || 'Code Craftsman'}`, 14, 80);

    doc.setTextColor(150, 150, 162);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    const archLines = doc.splitTextToSize(archetype.description || '', 180);
    doc.text(archLines, 14, 86);

    // Core Metrics
    doc.setDrawColor(39, 39, 46);
    doc.line(14, 102, 196, 102);

    doc.setTextColor(240, 240, 243);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(12);
    doc.text('CORE REPOSITORY METRICS', 14, 112);

    doc.setFont('courier', 'normal');
    doc.setFontSize(10);
    doc.text(`- Repositories: ${full(stats.own_repos || 0)} own / ${full(stats.forked_repos || 0)} forked`, 14, 122);
    doc.text(`- Total Stars:  ${full(stats.total_stars || 0)}`, 14, 130);
    doc.text(`- Followers:    ${full(profile.followers || 0)}`, 14, 138);
    doc.text(`- Following:    ${full(profile.following || 0)}`, 14, 146);

    // Top Languages
    const langs = Object.entries(dossier.languages || {}).slice(0, 5);
    doc.text(`- Languages:    ${langs.map(([l, b]) => `${l} (${compact(b)} KB)`).join(', ') || 'N/A'}`, 14, 154);

    // Footer
    doc.setDrawColor(39, 39, 46);
    doc.line(14, 275, 196, 275);
    doc.setTextColor(82, 82, 94);
    doc.setFontSize(8);
    doc.text(`Generated by Git-Spectre · https://git-spectre.vercel.app/?u=${profile.login}`, 14, 283);

    doc.save(`git-spectre-${profile.login}.pdf`);
    showToast('PDF downloaded successfully', 'check');
  } catch (err) {
    showToast(`PDF Export failed: ${err.message}`, 'alert-triangle');
  }
}

export async function exportShareCard(dossier) {
  if (!dossier || !dossier.profile) {
    showToast('No profile scanned yet', 'alert-triangle');
    return;
  }

  showToast('Generating shareable card…', 'image');
  const card = document.getElementById('shareCardOffscreen');
  if (!card) return;

  const profile = dossier.profile;
  const score = dossier.score || {};
  const arch = dossier.archetype || {};
  const stats = dossier.stats || {};
  const langs = Object.entries(dossier.languages || {}).slice(0, 4);

  // Populate hidden offscreen card
  document.getElementById('scAvatar').src = avatarUrl(profile.login, 120);
  document.getElementById('scName').textContent = profile.name || profile.login;
  document.getElementById('scLogin').textContent = `@${profile.login}`;
  document.getElementById('scScore').textContent = score.total || 0;
  document.getElementById('scGrade').textContent = score.grade || 'E';
  document.getElementById('scArchetype').textContent = arch.label || 'Code Craftsman';

  const langsContainer = document.getElementById('scLangs');
  if (langsContainer) {
    langsContainer.innerHTML = langs.map(([l]) => `
      <span style="font-family:'JetBrains Mono',monospace;font-size:11px;background:rgba(255,255,255,0.08);padding:3px 8px;border-radius:6px;margin-right:6px">
        ${l}
      </span>
    `).join('');
  }

  const statsContainer = document.getElementById('scStats');
  if (statsContainer) {
    statsContainer.innerHTML = `
      <span style="display:flex;align-items:center;gap:4px">${icon('star', 'w-3.5 h-3.5')} ${compact(stats.total_stars || 0)} Stars</span>
      <span style="display:flex;align-items:center;gap:4px">${icon('users', 'w-3.5 h-3.5')} ${compact(profile.followers || 0)} Followers</span>
      <span style="display:flex;align-items:center;gap:4px">${icon('package', 'w-3.5 h-3.5')} ${compact(stats.own_repos || 0)} Repos</span>
    `;
  }

  try {
    const canvas = await window.html2canvas(card, {
      scale: 2,
      useCORS: true,
      backgroundColor: '#09090b',
    });
    const link = document.createElement('a');
    link.download = `git-spectre-${profile.login}.png`;
    link.href = canvas.toDataURL('image/png');
    link.click();
    showToast('Share card downloaded', 'check');
  } catch (err) {
    showToast(`Card creation failed: ${err.message}`, 'alert-triangle');
  }
}

export function copyBadgeSnippet(login) {
  if (!login) return;
  const snippet = `[![Git-Spectre](https://git-spectre.vercel.app/api/badge/${login})](https://git-spectre.vercel.app/?u=${login})`;
  navigator.clipboard.writeText(snippet)
    .then(() => showToast('Badge markdown copied to clipboard!', 'copy'))
    .catch(() => showToast('Could not copy badge', 'alert-triangle'));
}
